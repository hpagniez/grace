async function read(file: string, readFile?: () => Promise<string>): Promise<Api> {
  const r = await readApi(
    { kind: "file", path: fixture(file) },
    { fetch: globalThis.fetch, signal: new AbortController().signal, readFile },
  );
  if (!("api" in r)) throw new Error(`failed:\n${r.errors.join("\n")}`);
  return r.api;
}
