const schema = (s: Partial<Schema> = {}): Schema => ({
  types: [],
  nullable: false,
  properties: null,
  required: [],
  items: null,
  allOf: [],
  oneOf: [],
  anyOf: [],
  format: null,
  minimum: null,
  readOnly: false,
  writeOnly: false,
  samples: [],
  ...s,
});
const param = (p: Partial<Param> & Pick<Param, "name">): Param => ({
  in: "query",
  required: false,
  samples: [],
  schema: null,
  ...p,
});
const op = (o: Partial<Operation> = {}): Operation => ({
  method: "get",
  path: "/things",
  tag: null,
  summary: null,
  params: [],
  body: null,
  success: { code: "200", body: null },
  security: [],
  ...o,
});
const api = (operations: Operation[], a: Partial<Api> = {}): Api => ({
  title: "T",
  version: "1",
  server: null,
  tags: [],
  operations,
  ...a,
});

const str = schema({ types: ["string"] });
const int = schema({ types: ["integer"] });
const num = schema({ types: ["number"] });
const bool = schema({ types: ["boolean"] });
const arr = (items: Schema | null = null) => schema({ types: ["array"], items });
const obj = (properties: Record<string, Schema> | null = null, required: string[] = []) =>
  schema({ types: ["object"], properties, required });
const json = (s: Schema | null, samples: unknown[] = []): Body => ({
  mediaType: "application/json",
  json: true,
  samples,
  schema: s,
});
const req = (name: string, s: Schema | null, samples: unknown[] = [], where = "query") =>
  param({ name, in: where as Param["in"], required: true, schema: s, samples });

/** The one scenario of an API with one operation: its lines, trimmed, from `Scenario:` on. */
function scenario(o: Operation, a?: Partial<Api>): string[] {
  const lines = generate(api([o], a), O)[0]!.text.split("\n");
  const start = lines.findIndex((l) => l.startsWith("  Scenario:"));
  return lines
    .slice(start)
    .filter(Boolean)
    .map((l) => l.trim());
}
/** The JSON after `keyword` on the scenario's step that starts with it. */
function jsonAfter(lines: string[], keyword: string): unknown {
  const found = lines.find((l) => l.startsWith(keyword));
  if (!found) throw new Error(`no ${keyword} in\n${lines.join("\n")}`);
  return JSON.parse(found.slice(keyword.length));
}
