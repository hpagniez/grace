describe("generate: path segments", () => {
  const pathOf = (o: Partial<Operation>) =>
    scenario(op(o)).find((l) => l.startsWith("Given path")) ?? null;

  it("drops empty segments", () => {
    expect(pathOf({ path: "/pets/" })).toBe('Given path "pets"');
    expect(pathOf({ path: "//a" })).toBe('Given path "a"');
    expect(pathOf({ path: "/" })).toBeNull();
  });

  it("keeps a segment that is not ASCII", () => {
    expect(pathOf({ path: "/città/{id}", params: [req("id", int, [], "path")] })).toBe(
      'Given path "città", 0',
    );
  });

  it("puts a parameter inside a segment that holds other text into one string", () => {
    const params = [req("name", str, ["report"], "path")];
    expect(pathOf({ path: "/files/{name}.json", params })).toBe('Given path "files", "report.json"');
    const two = [req("from", int, [1], "path"), req("to", int, [9], "path")];
    expect(pathOf({ path: "/range/{from}-{to}", params: two })).toBe('Given path "range", "1-9"');
  });

  it("writes a parameter that is a whole segment as its own JSON value", () => {
    const at = (sample: unknown) =>
      pathOf({ path: "/a/{p}", params: [req("p", null, [sample], "path")] });
    expect(at(5)).toBe('Given path "a", 5');
    expect(at("x y")).toBe('Given path "a", "x y"');
    expect(at(true)).toBe('Given path "a", true');
    expect(at({ k: 1 })).toBe('Given path "a", "{\\"k\\":1}"');
  });

  it("gives a path parameter with no schema and no sample the string", () => {
    expect(pathOf({ path: "/pets/{petId}", params: [req("petId", null, [], "path")] })).toBe(
      'Given path "pets", "string"',
    );
    expect(pathOf({ path: "/pets/{petId}" })).toBe('Given path "pets", "string"');
  });

  it("escapes a segment as a JSON string", () => {
    expect(pathOf({ path: '/a"b/c\\d' })).toBe('Given path "a\\"b", "c\\\\d"');
  });
});

describe("generate: the response match (R5.4)", () => {
  const match = (s: Schema) => scenario(op({ success: { code: "200", body: json(s) } })).at(-1);
  const OBJECT = "And match response contains deep ";
  /** The marker of one property `p` of an object response. */
  const prop = (s: Schema, isRequired: boolean) =>
    JSON.parse(match(obj({ p: s }, isRequired ? ["p"] : []))!.slice(OBJECT.length)).p;

  it.each([
    ["a string", str, 'And match response == "#string"'],
    ["an integer", int, 'And match response == "#number"'],
    ["a number", num, 'And match response == "#number"'],
    ["a boolean", bool, 'And match response == "#boolean"'],
    ["an array", arr(), 'And match response == "#array"'],
    ["an array of strings", arr(str), 'And match response == "#[] #string"'],
    ["an object without properties", obj(), 'And match response == "#object"'],
    ["an array of such objects", arr(obj()), 'And match response == "#array"'],
    ["an object", obj({ a: str, b: int }, ["a"]), `${OBJECT}{"a":"#string","b":"##number"}`],
    [
      "an array of objects",
      arr(obj({ a: str }, ["a"])),
      'And match each response contains deep {"a":"#string"}',
    ],
    ["a oneOf", schema({ oneOf: [obj({ a: str })] }), 'And match response == "#present"'],
    ["a nullable object", { ...obj({ a: str }), nullable: true }, 'And match response == "##object"'],
  ])("matches %s", (_, s, expected) => {
    expect(match(s)).toBe(expected);
  });

  it.each([
    ["a string", str, "#string", "##string"],
    ["an integer", int, "#number", "##number"],
    ["a number", num, "#number", "##number"],
    ["a boolean", bool, "#boolean", "##boolean"],
    ["an array", arr(), "#array", "##array"],
    ["an array of strings", arr(str), "#[] #string", "##[] #string"],
    ["an array of integers", arr(int), "#[] #number", "##[] #number"],
    ["an array of booleans", arr(bool), "#[] #boolean", "##[] #boolean"],
    ["an array of objects", arr(obj({ a: str })), "#array", "##array"],
    ["an array of nullable strings", arr(schema({ ...str, nullable: true })), "#array", "##array"],
    ["an object", obj(), "#object", "##object"],
    ["a nullable string", schema({ ...str, nullable: true }), "##string", "##string"],
    ["a oneOf", schema({ oneOf: [str, int] }), "#present", "#ignore"],
    ["an anyOf", schema({ anyOf: [str, int] }), "#present", "#ignore"],
    ["a list of types", schema({ types: ["string", "integer"] }), "#present", "#ignore"],
    ["a schema that says nothing", schema(), "#present", "#ignore"],
    ["a schema that allows only null", schema({ nullable: true }), "#null", "##null"],
  ])("marks a property that is %s", (_, s, whenRequired, whenOptional) => {
    expect(prop(s, true)).toBe(whenRequired);
    expect(prop(s, false)).toBe(whenOptional);
  });

  it("writes a required object with properties as an object, an optional one as ##object", () => {
    const inner = obj({ x: str, y: int }, ["x"]);
    expect(prop(inner, true)).toEqual({ x: "#string", y: "##number" });
    expect(prop(inner, false)).toBe("##object");
    expect(prop(schema({ ...inner, nullable: true }), true)).toBe("##object");
  });

  it("merges allOf, its properties and its required", () => {
    const s = schema({ allOf: [obj({ a: str }, ["a"]), obj({ b: int })] });
    expect(match(s)).toBe(`${OBJECT}{"a":"#string","b":"##number"}`);
  });

  it("treats a nullable allOf wrapper as nullable", () => {
    const s = schema({ nullable: true, allOf: [obj({ a: str }, ["a"])] });
    expect(prop(s, true)).toBe("##object");
  });

  it("leaves out a property that only a request holds", () => {
    const s = obj({ password: schema({ ...str, writeOnly: true }), a: str }, ["password", "a"]);
    expect(match(s)).toBe(`${OBJECT}{"a":"#string"}`);
  });

  it("nests objects down to 5 levels, then writes #object", () => {
    const chain = (n: number): Schema => (n === 0 ? str : obj({ c: chain(n - 1) }, ["c"]));
    expect(match(chain(7))).toBe(`${OBJECT}{"c":{"c":{"c":{"c":{"c":"#object"}}}}}`);
    expect(match(chain(5))).toBe(`${OBJECT}{"c":{"c":{"c":{"c":{"c":"#string"}}}}}`);
  });

  it("writes #ignore for a schema met again on its own path", () => {
    const node = obj({ value: str }, ["value"]);
    node.properties!.next = node;
    node.required.push("next");
    expect(match(node)).toBe(`${OBJECT}{"value":"#string","next":"#ignore"}`);
  });

  it("keeps a response with many fanning-out objects short", () => {
    let level = obj({ x: str }, ["x"]);
    for (let i = 0; i < 4; i++) {
      const keys = Array.from({ length: 20 }, (_, k) => `p${k}`);
      level = obj(Object.fromEntries(keys.map((k) => [k, level])), keys);
    }
    const start = performance.now();
    const line = match(level)!;
    expect(performance.now() - start).toBeLessThan(1000);
    expect(line.length).toBeLessThan(500_000);
  });

  it("leaves out a property whose name Karate would read as an expression", () => {
    const s = obj({ "#(karate.exec('k'))": str, ok: str }, ["ok"]);
    expect(match(s)).toBe(`${OBJECT}{"ok":"#string"}`);
  });
});

describe("generate: values (R5.5)", () => {
  const sending = (s: Schema | null, samples: unknown[] = []) =>
    jsonAfter(scenario(op({ method: "post", body: json(s, samples) })), "And request ");
  const sent = (...params: Param[]) => jsonAfter(scenario(op({ params })), "And params ");

  it("takes each source in its order, and the first sample of the one that has any", async () => {
    const a = await readText(`
openapi: 3.1.0
info: { title: T, version: "1" }
paths:
  /values:
    get:
      parameters:
        - { name: a, in: query, required: true, example: 7, schema: { type: integer, example: 8 } }
        - name: b
          in: query
          required: true
          examples: { first: { value: 9 } }
          schema: { type: integer, example: 8 }
        - { name: c, in: query, required: true, schema: { type: integer, example: 1, default: 2 } }
        - { name: d, in: query, required: true, schema: { type: integer, examples: [3, 4] } }
        - { name: e, in: query, required: true, schema: { type: string, const: k, default: z } }
        - { name: f, in: query, required: true, schema: { type: string, default: d, enum: [x, y] } }
        - { name: g, in: query, required: true, schema: { type: string, enum: [x, y] } }
      responses:
        "200": { description: ok }
`);
    expect(jsonAfter(scenario(a.operations[0]!), "And params ")).toEqual({
      a: 7,
      b: 9,
      c: 1,
      d: 3,
      e: "k",
      f: "d",
      g: "x",
    });
  });

  it("falls back to a placeholder by type, and by format", () => {
    const string = (format: string) => schema({ ...str, format });
    expect(
      sent(
        req("s", str),
        req("date", string("date")),
        req("time", string("date-time")),
        req("mail", string("email")),
        req("id", string("uuid")),
        req("url", string("uri")),
        req("bin", string("binary")),
        req("proto", string("constructor")),
        req("n", num),
        req("i", int),
        req("min", schema({ ...int, minimum: 5 })),
        req("neg", schema({ ...num, minimum: -3 })),
        req("b", bool),
        req("list", arr(str)),
        req("bare", arr()),
        req("o", obj({ a: int, s: str })),
        req("none", null),
      ),
    ).toEqual({
      s: "string",
      date: "2026-01-01",
      time: "2026-01-01T00:00:00Z",
      mail: "user@example.com",
      id: "00000000-0000-0000-0000-000000000000",
      url: "https://example.com",
      bin: "string",
      proto: "string",
      n: 0,
      i: 0,
      min: 5,
      neg: 0,
      b: true,
      list: ["string"],
      bare: [],
      o: { a: 0, s: "string" },
      none: "string",
    });
  });

  it("prefers the parameter's sample to the schema's", () => {
    const withSample = schema({ ...int, samples: [8] });
    expect(sent(req("a", withSample, [7]), req("b", withSample))).toEqual({ a: 7, b: 8 });
  });

  it("takes a property's own sample inside an object", () => {
    expect(sending(obj({ id: schema({ ...int, samples: [1] }), name: str }))).toEqual({
      id: 1,
      name: "string",
    });
  });

  it("prefers the media type's sample to the schema", () => {
    expect(sending(obj({ a: str }), [{ custom: 1 }])).toEqual({ custom: 1 });
  });

  it("leaves readOnly properties out of a request", () => {
    const s = obj({ id: schema({ ...int, readOnly: true }), name: str });
    expect(sending(s)).toEqual({ name: "string" });
  });

  it("merges allOf and takes the first of oneOf and anyOf", () => {
    expect(sending(schema({ allOf: [obj({ a: str }), obj({ b: int })] }))).toEqual({
      a: "string",
      b: 0,
    });
    expect(sending(schema({ oneOf: [obj({ x: str }), obj({ y: int })] }))).toEqual({ x: "string" });
    expect(sending(schema({ anyOf: [int, str] }))).toBe(0);
  });

  it("writes null for a schema met again on its own path", () => {
    const node = obj({ value: str });
    node.properties!.next = node;
    expect(sending(node)).toEqual({ value: "string", next: null });
    const pet = obj({ name: str });
    pet.properties!.friends = arr(pet);
    expect(sending(pet)).toEqual({ name: "string", friends: [null] });
    const list = arr();
    list.items = list;
    expect(sending(list)).toEqual([null]);
  });

  it("nests objects down to 5 levels, then writes {}", () => {
    const chain = (n: number): Schema => (n === 0 ? str : obj({ c: chain(n - 1) }));
    expect(sending(chain(7))).toEqual({ c: { c: { c: { c: { c: {} } } } } });
    expect(sending(chain(5))).toEqual({ c: { c: { c: { c: { c: "string" } } } } });
  });

  it("keeps a request with many fanning-out objects short", () => {
    let level = obj({ x: str });
    for (let i = 0; i < 4; i++) {
      const keys = Array.from({ length: 20 }, (_, k) => `p${k}`);
      level = obj(Object.fromEntries(keys.map((k) => [k, level])));
    }
    const start = performance.now();
    const text = JSON.stringify(sending(level));
    expect(performance.now() - start).toBeLessThan(1000);
    expect(text.length).toBeLessThan(500_000);
  });

  it("writes a body with no schema and no sample as the placeholder string", () => {
    expect(sending(null)).toBe("string");
  });
});

describe("generate: the spec's text is data (R6)", () => {
  it("keeps a spec's text out of the steps", async () => {
    const files = generate(await read("hostile.yaml"), { source: "hostile.yaml", date: "2026-11-04" });
    expect(files.map((f) => f.name)).toEqual([
      "pets.feature",
      "ascenario-b.feature",
      "linesep.feature",
    ]);
    const text = files.map((f) => f.text).join("");
    const lines = text.split("\n");

    // A name loses its line breaks; it does not start a line.
    expect(lines[0]).toBe("# Generated by Grace from hostile.yaml on 2026-11-04: HostileScenario: z 1");
    expect(lines.filter((l) => l.startsWith("Feature:"))).toEqual([
      "Feature: pets",
      "Feature: aScenario: b",
      "Feature: linesep",
    ]);
    // A description is only comments.
    expect(lines).toContain("  # Scenario: x");
    expect(lines).toContain("  # * karate.exec('calc')");
    expect(lines).toContain("  # List");
    expect(lines).toContain("  # * karate.exec('summary')");
    expect(lines).toContain("    # Security: k* karate.exec('security')");
    // Nothing but a comment, or a step this generator writes, is on any line.
    const shape =
      /^(Feature: .*|  Background:|    \* url karate\.get\("baseUrl", "[^"]*"\)|  Scenario: [A-Z]+ \/.*|    (Given path|And params|And headers|And request|When method|Then status|Then assert|And match) .*)$/;
    for (const l of lines) if (l.trim() !== "" && !l.trim().startsWith("#")) expect(l).toMatch(shape);
    expect(lines.filter((l) => !l.trim().startsWith("#") && l.includes("karate.exec"))).toEqual([]);
    expect(text).not.toMatch(/[\u0085  ]/);
    // A value that Karate would evaluate becomes the placeholder; a name that it would, is left out.
    const pets = files[0]!.text;
    expect(pets).toContain('    Given path "pets", "string"\n');
    expect(pets).toContain('    And request {"name":"string","nested":{"n":"string"}}\n');
    expect(pets).not.toContain("And params");
    expect(pets).toContain('    * url karate.get("baseUrl", "http://hostile.example/a\\u2028b")\n');
  });

  it("replaces a string value that starts with #, or holds #(, anywhere in a sample", () => {
    const sample = { a: " #(x)", b: ["##string", "ok", "a#b", "x #(y)"], "#(k)": 1, n: 5 };
    const o = op({ method: "post", body: json(null, [sample]) });
    expect(jsonAfter(scenario(o), "And request ")).toEqual({
      a: "string",
      b: ["string", "ok", "a#b", "string"],
      n: 5,
    });
  });

  it("replaces such a value in a parameter and in a path", () => {
    const lines = scenario(
      op({
        path: "/a/{p}",
        params: [req("p", null, ["#(x)"], "path"), req("q", null, ["#string"])],
      }),
    );
    expect(lines).toContain('Given path "a", "string"');
    expect(lines).toContain('And params {"q":"string"}');
  });

  it("escapes the line breaks that JSON leaves as they are", () => {
    const o = op({ method: "post", body: json(null, ["a\u0085b c d\u007fe\nf"]) });
    const text = generate(api([o]), O)[0]!.text;
    expect(text).toContain('And request "a\\u0085b\\u2028c\\u2029d\\u007fe\\nf"\n');
    expect(text).not.toMatch(/[\u0085  \u007f]/);
  });

  it("drops control characters from names, comments and the source", () => {
    const a = api([op({ summary: "s\u0007ummary\r\n* karate.exec('s')", tag: "t\u0000ag", path: "/p\u001b" })], {
      title: "ti\ttle",
      version: "1‮",
    });
    const text = generate(a, { source: "a\nb.yaml", date: "2026-11-04" })[0]!.text;
    expect(text.split("\n")[0]).toBe("# Generated by Grace from ab.yaml on 2026-11-04: title 1");
    expect(text).toContain("\nFeature: tag\n");
    expect(text).toContain("\n  # summary\n  # * karate.exec('s')\n  Scenario: GET /p\n");
    expect([...text].filter((c) => c < " " && c !== "\n")).toEqual([]);
    expect(text).not.toContain("‮");
  });

  it("writes a name only on one line however the spec breaks it", () => {
    const a = api([op({ tag: "a\r\nScenario: b" }), op({ tag: "c d", path: "/x" })]);
    expect(generate(a, O).map((f) => f.text.split("\n")[1])).toEqual([
      "Feature: aScenario: b",
      "Feature: cd",
    ]);
  });

  it("writes the server as a JSON string", () => {
    const text = generate(api([op()], { server: 'http://x/"); karate.exec("calc' }), O)[0]!.text;
    expect(text).toContain('* url karate.get("baseUrl", "http://x/\\"); karate.exec(\\"calc")\n');
  });

  it("ends a file with one \\n, no byte order mark and no \\r", () => {
    const text = generate(api([op({ summary: "a\r\nb" })]), O)[0]!.text;
    expect(text.endsWith("\n")).toBe(true);
    expect(text.endsWith("\n\n")).toBe(false);
    expect(text).not.toContain("\r");
    expect(text.charCodeAt(0)).not.toBe(0xfeff);
  });
});

